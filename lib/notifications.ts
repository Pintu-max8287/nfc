/**
 * lib/notifications.ts — DineFlow Modular WhatsApp Notification Engine
 * Supports Meta WhatsApp Cloud API via WHATSAPP_API_TOKEN & WHATSAPP_PHONE_ID,
 * with graceful SIMULATED logging into PostgreSQL NotificationLog.
 */
import { prisma } from "@/lib/prisma";

export type NotificationType = "NEW_ORDER" | "LOW_STOCK" | "DAILY_REPORT";

export interface SendNotificationParams {
  restaurantId: string;
  type: NotificationType;
  recipient: string;
  message: string;
}

export interface NotificationResult {
  success: boolean;
  status: "SENT" | "SIMULATED" | "FAILED";
  error?: string;
}

/**
 * Dispatches a WhatsApp notification.
 * If Meta WhatsApp credentials exist and are non-dummy, sends via Cloud API.
 * Otherwise, records as SIMULATED so all notifications can be verified in the Admin dashboard.
 */
export async function sendNotification({
  restaurantId,
  type,
  recipient,
  message,
}: SendNotificationParams): Promise<NotificationResult> {
  const token = process.env.WHATSAPP_API_TOKEN;
  const phoneId = process.env.WHATSAPP_PHONE_ID;

  let status: "SENT" | "SIMULATED" | "FAILED" = "SIMULATED";
  let errorMsg: string | undefined;

  // Real WhatsApp Cloud API dispatch
  if (
    token &&
    phoneId &&
    token !== "your-meta-whatsapp-cloud-api-bearer-token" &&
    recipient
  ) {
    try {
      const cleanPhone = recipient.replace(/[^0-9]/g, "");
      const res = await fetch(
        `https://graph.facebook.com/v21.0/${phoneId}/messages`,
        {
          method: "POST",
          headers: {
            Authorization: `Bearer ${token}`,
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            messaging_product: "whatsapp",
            to: cleanPhone,
            type: "text",
            text: { body: message },
          }),
        }
      );

      if (res.ok) {
        status = "SENT";
      } else {
        const errorText = await res.text();
        console.warn("[WhatsApp Cloud API Error]:", errorText);
        status = "FAILED";
        errorMsg = errorText;
      }
    } catch (err) {
      console.warn("[WhatsApp Network]:", err);
      status = "FAILED";
      errorMsg = err instanceof Error ? err.message : "Network error";
    }
  }

  // Record in NotificationLog
  try {
    await prisma.notificationLog.create({
      data: {
        restaurantId,
        type,
        recipient: recipient || "Unconfigured",
        message,
        status,
      },
    });
  } catch (err) {
    console.error("Failed to write to NotificationLog:", err);
  }

  return { success: status !== "FAILED", status, error: errorMsg };
}

/** Trigger 1: New Order Alert */
export async function notifyNewOrder(
  restaurant: { id: string; name: string; currencySymbol: string; whatsappNumber: string | null },
  orderNumber: number,
  tableNumber: string,
  totalAmount: number,
  itemCount: number
) {
  const recipient = restaurant.whatsappNumber || "Owner";
  const msg = `🔔 New Order #${orderNumber} received for Table ${tableNumber}!\n` +
    `Total: ${restaurant.currencySymbol}${totalAmount.toFixed(2)} (${itemCount} items).\n` +
    `Status: Sent to Kitchen Display.`;

  return sendNotification({
    restaurantId: restaurant.id,
    type: "NEW_ORDER",
    recipient,
    message: msg,
  });
}

/** Trigger 2: Low-Stock Warning */
export async function notifyLowStock(
  restaurant: { id: string; whatsappNumber: string | null },
  dishName: string,
  remainingPortions: number
) {
  const recipient = restaurant.whatsappNumber || "Owner";
  const msg = `⚠️ Low Stock Warning: "${dishName}" has only ${remainingPortions} portions left in stock!`;

  return sendNotification({
    restaurantId: restaurant.id,
    type: "LOW_STOCK",
    recipient,
    message: msg,
  });
}

/** Trigger 3: EOD Daily Sales Report */
export async function notifyDailyReport(
  restaurant: { id: string; name: string; currencySymbol: string; whatsappNumber: string | null },
  stats: {
    dateStr: string;
    totalOrders: number;
    paidOrders: number;
    totalRevenue: number;
    topDish?: string;
  }
) {
  const recipient = restaurant.whatsappNumber || "Owner";
  const msg = `📊 End-of-Day Sales Report — ${restaurant.name}\n` +
    `Date: ${stats.dateStr}\n` +
    `━━━━━━━━━━━━━━━━━━━━━━\n` +
    `• Total Orders: ${stats.totalOrders}\n` +
    `• Paid Orders: ${stats.paidOrders}\n` +
    `• Total Revenue: ${restaurant.currencySymbol}${stats.totalRevenue.toFixed(2)}\n` +
    (stats.topDish ? `• Top Selling Dish: ${stats.topDish}\n` : "") +
    `━━━━━━━━━━━━━━━━━━━━━━\n` +
    `Generated by DineFlow Automation.`;

  return sendNotification({
    restaurantId: restaurant.id,
    type: "DAILY_REPORT",
    recipient,
    message: msg,
  });
}

